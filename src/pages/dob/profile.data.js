// Тыс. т в год по АО «Озенмунайгаз»; для других активов масштабируется коэффициентом актива.
// 2022–2025 — факт, 2026 — оценка (13 817 т/сут в сводке за 02.11 × 365), 2027–2031 — прогноз ПДИМ 2.0.
// Базовая добыча 2027 — 4 860 тыс. т (скользящий год с переходящим эффектом мероприятий 2026), далее падение 6,1 % в год;
// компоненты ГТМ, ВНС и МУН — эффект в году ввода и переходящий эффект прошлых лет (годовой эффект программы ГТМ 2027 — 412,0 тыс. т).
import { sum } from '../../lib/format.js';

export const YEARS = ['2022', '2023', '2024', '2025', '2026', '2027', '2028', '2029', '2030', '2031'];
export const FC = 5; // индекс 2027 — начало прогноза
export const KP = 0.939; // коэффициент падения базовой добычи (6,1 % в год)
const BASE = [5351, 5229, 5091, 4980, 4874, 4860];
const GTM = [120, 128, 131, 126, 124, 112, 268, 392, 488, 560];
const VNS = [41, 44, 46, 43, 45, 34, 101, 158, 205, 243];
const MUN = [0, 0, 0, 0, 0, 4, 18, 41, 66, 88];
// v: 0 — базовый вариант, 1 — расширенная программа ГТМ, 2 — полимерное заводнение (МУН)
export function profile(k = 1, v = 0) {
  const base = YEARS.map((_, i) => Math.round((i <= FC ? BASE[i] : BASE[FC] * Math.pow(KP, i - FC)) * k));
  const gtm = GTM.map((x, i) => Math.round(x * (v === 1 && i > FC ? 1.25 : 1) * k));
  const vns = VNS.map((x) => Math.round(x * k));
  const mun = MUN.map((x, i) => Math.round(x * (v === 2 && i > FC ? 2.2 : 1) * k));
  return { base, gtm, vns, mun, tot: YEARS.map((_, i) => base[i] + gtm[i] + vns[i] + mun[i]) };
}
export const sum5 = (p) => sum(p.tot.slice(FC));
export const VN = ['Вариант 1 · базовый', 'Вариант 2 · расширенная программа ГТМ', 'Вариант 3 · полимерное заводнение (МУН)'];
export const VECO = [{ capex: 412.6, npv: 186.4 }, { capex: 468.3, npv: 192.1 }, { capex: 521.9, npv: 171.8 }];
export const variants = (k = 1) => [0, 1, 2].map((v) => { const p = profile(k, v); return { id: v, name: VN[v], prod: sum5(p), ...VECO[v], p }; });
// Коэффициенты по годам: падения (к предыдущему году; в 2027 — базовая к общей добыче 2026), эксплуатации
export function coefs(k = 1) {
  const p = profile(k, 0);
  return YEARS.map((y, i) => ({ id: y, y, kp: i === 0 ? null : i === FC ? +(p.base[i] / p.tot[i - 1]).toFixed(3) : i > FC ? KP : +(p.tot[i] / p.tot[i - 1]).toFixed(3), ke: +(0.951 + Math.sin(i * 1.7) * 0.008).toFixed(3), tot: p.tot[i], kind: y === '2026' ? 'оценка' : i < FC ? 'факт' : 'прогноз' }));
}
