// Рентабельность скважин (ДБиИА): нерентабельные и на границе рентабельности
export function unprofitable(n = 6) {
  const r = rng('rent');
  return WELLS.filter((w) => w.type === 'prod' && w.status === 'work' && w.qO > 0 && w.qO < 4).sort((a, b) => a.qO - b.qO).slice(0, n)
    .map((w) => ({ id: w.id, w: w.id, ngdu: w.ngdu, q: w.qO, cost: Math.round(52 + r() * 30), mar: Math.round((w.qO * 0.112 - 0.42) * 1000) / 10 }));
}

// Скважины с потерями и мероприятия по ним
const WHY = (w) => (w.status === 'idle' ? 'Простой' : w.status === 'repair' ? 'Ремонт (ТКРС)' : w.dev ? 'Отклонение от режима' : 'Риск отказа ГНО');
export function losses() {
  return WELLS.filter((w) => w.type === 'prod' && (w.status === 'idle' || w.status === 'repair' || w.dev || w.risk > 70)).map((w) => {
    const why = WHY(w);
    const loss = +(w.status === 'idle' || w.status === 'repair' ? w.qO : w.dev ? w.qO * 0.32 : w.qO * 0.12).toFixed(1);
    return { id: w.id, w, ngdu: w.ngdu, why, loss };
  }).sort((a, b) => b.loss - a.loss);
}
